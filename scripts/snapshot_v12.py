"""Write site/src/snap12.js: the brain's self-checks (brain_robust.py on the shipped series) and the voices library
with its retrieval configuration, so the page works before any daily run.

    python scripts/snapshot_v12.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from buildout import brain_robust, voices  # noqa: E402
from buildout.brain import PARENTS, REGIMES  # noqa: E402


def _clean(o):
    if isinstance(o, float):
        return None if o != o or o in (float("inf"), float("-inf")) else round(o, 6)
    if isinstance(o, dict):
        return {str(k): _clean(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [_clean(v) for v in o]
    return o


def main() -> int:
    series = json.loads((ROOT / "buildout" / "assets" / "brain_graph.json").read_text())["series"]
    r = brain_robust.analyze(series, PARENTS, REGIMES)
    r["findings"] = brain_robust.summary(r)
    p = ROOT / "buildout" / "assets" / "voices.json"
    lib = json.loads(p.read_text()) if p.exists() else {"quotes": []}
    out = ROOT / "site" / "src" / "snap12.js"
    js = ("  /* snap12.js (v0.12, generated by scripts/snapshot_v12.py; do not edit): the brain's self-checks on the shipped\n"
          "     series, and the verified voices library with the retrieval configuration buildout/voices.py uses. */\n"
          f"  const ROBUST_SNAP = {json.dumps(_clean(r), separators=(',', ':'), ensure_ascii=False)};\n"
          f"  const VOICES_CFG = {json.dumps(_clean(voices.config()), separators=(',', ':'), ensure_ascii=False)};\n"
          f"  const VOICES_LIB = {json.dumps(_clean(lib), separators=(',', ':'), ensure_ascii=False)};\n")
    out.write_text(js)
    print(f"wrote {out} {len(js):,} bytes; {len(lib.get('quotes', []))} quotes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
