"""Write site/src/snap27.js (v0.27: the nowcast: early-published facts against the book's next quarterly reports,
whether they forecast revenue, whether the market had priced them, and each holding's next report) and rebuild snap14
to snap26 through snapshot_v26. Derived results only: the mirror's prices and filings stay in the run's cache.

    python scripts/snapshot_v27.py --nowcast-json nowcast_o.json ... (the v26 flags)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

from buildout import nowcast  # noqa: E402
import snapshot_v14 as S14  # noqa: E402
import snapshot_v15 as S15  # noqa: E402
import snapshot_v26 as S26  # noqa: E402

S15.EXTRA_CODE += ["buildout/nowcast.py", "scripts/snapshot_v27.py"]


def main(argv: list[str]) -> int:
    S26.main(argv)
    o = json.loads(Path(argv[argv.index("--nowcast-json") + 1]).read_text())
    o["findings"] = nowcast.summary(o)
    s = json.dumps(S14._clean({"nowcast": o}), separators=(",", ":"), ensure_ascii=False).replace("</", "<\\/")
    for b in S14.BANNED:
        assert b not in s.lower(), b
    (ROOT / "site" / "src" / "snap27.js").write_text("  /* snap27.js (v0.27, generated by scripts/snapshot_v27.py; do not edit): the nowcast. Derived results only. */\n"
                                                     f"  const SNAP27 = {s};\n")
    print("snap27.js", len(s) // 1024, "KB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
