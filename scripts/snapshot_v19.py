"""Write site/src/snap19.js (the decision engine: today's decision, its inference, models and walk-forward record) and
rebuild snap14 to snap17 through snapshot_v17 with the decision in the mind. Derived results only.

    python scripts/snapshot_v19.py --dec-pickle dec_o.pkl --labs-cache labs_dl.pkl --labs-pickle labs_L.pkl --ml-pickle ml_o.pkl \\
        --as-pickle as_o.pkl --rl-pickle rl_o.pkl --cx-pickle cx_o.pkl
"""
from __future__ import annotations

import json
import pickle
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

from buildout import decide, labs, mind  # noqa: E402
import snapshot_v14 as S14  # noqa: E402
import snapshot_v15 as S15  # noqa: E402
import snapshot_v17 as S17  # noqa: E402

S15.EXTRA_CODE += ["buildout/decide.py", "buildout/infer.py", "buildout/nn.py", "scripts/snapshot_v19.py"]


def main(argv: list[str]) -> int:
    get = lambda k: pickle.loads(Path(argv[argv.index(k) + 1]).read_bytes()) if k in argv and Path(argv[argv.index(k) + 1]).exists() else None
    dec = get("--dec-pickle")
    if dec is None:
        dl = get("--labs-cache") or labs.download()
        K = {k["id"]: k for k in mind.load_knowledge()}
        dec = decide.build(dl, cape_now=(K.get("val-cape-2026-10-20") or {}).get("value"), y10_now=5.13)
    dec["findings"] = decide.summary(dec)                   # the wording follows the code, the numbers the run
    dec = S14._clean(dec)
    orig = mind.build
    mind.build = lambda *a, **kw: orig(*a, **kw, dec=dec)
    try:
        S17.main(argv)                                        # it ignores the flags it does not know
    finally:
        mind.build = orig
    body = json.dumps({"decision": dec}, separators=(",", ":"), ensure_ascii=False).replace("</", "<\\/")
    for b in S14.BANNED:
        assert b not in body.lower(), b
    out = ROOT / "site" / "src" / "snap19.js"
    out.write_text("  /* snap19.js (v0.19, generated by scripts/snapshot_v19.py; do not edit): the decision engine, from data to a sized,\n"
                   "     explained decision, walked forward from 1940. Derived results only. */\n"
                   f"  const SNAP19 = {body};\n  const DX19 = SNAP19.decision;\n")
    print("snap19.js", len(body) // 1024, "KB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
