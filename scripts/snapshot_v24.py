"""Write site/src/snap24.js (the research digest: every knowledge item dated in the last fortnight, with its source,
for the Research digest desk) and rebuild snap14 to snap23 through snapshot_v23, so the digest, the mind and the tape
all read the same knowledge store. Derived results only.

    python scripts/snapshot_v24.py --dec-pickle dec_o.pkl ... (the v23 flags) [--since 2026-10-13]
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

from buildout import mind  # noqa: E402
import snapshot_v14 as S14  # noqa: E402
import snapshot_v15 as S15  # noqa: E402
import snapshot_v23 as S23  # noqa: E402

S15.EXTRA_CODE += ["scripts/snapshot_v24.py"]
KEEP = ("id", "cluster", "kind", "ticker", "title", "text", "value", "unit", "as_of", "source_title", "source_url", "publisher", "primary", "verification", "concepts", "checked")
RESEARCH_CLUSTERS = ("tape", "capex_earnings", "ai_credit", "fed_inflation", "power", "distribution", "private_markets", "commodities")   # the bond-lab facts and the source profiles stay on their own desks


def digest(know: list[dict], since: str) -> dict:
    """items: the research clusters' items dated since `since` (the desk's listing); all: every item of those clusters,
    any date, so thesis cards and the Fundamentals desk can cite an older filing figure by id."""
    pool = [{k: x.get(k) for k in KEEP if x.get(k) is not None} for x in know
            if x.get("cluster") in RESEARCH_CLUSTERS and x.get("kind") in ("stat", "fact", "quote")]
    items = [x for x in pool if str(x.get("as_of") or "") >= since]
    items.sort(key=lambda x: (x["as_of"], x["id"]), reverse=True)
    older = sorted([x for x in pool if str(x.get("as_of") or "") < since], key=lambda x: (x.get("as_of") or "", x["id"]), reverse=True)
    pubs = sorted({x.get("publisher") for x in items if x.get("publisher")})
    by = {}
    for x in items:
        by[x["cluster"]] = by.get(x["cluster"], 0) + 1
    return {"since": since, "built": "2026-10-24", "items": items, "older": older, "publishers": pubs, "by_cluster": by, "n": len(items)}


def main(argv: list[str]) -> int:
    since = argv[argv.index("--since") + 1] if "--since" in argv else "2026-10-13"
    S23.main(argv)
    know = mind.load_knowledge()
    d = S14._clean(digest(know, since))
    body = json.dumps({"digest": d}, separators=(",", ":"), ensure_ascii=False).replace("</", "<\\/")
    for b in S14.BANNED:
        assert b not in body.lower(), b
    out = ROOT / "site" / "src" / "snap24.js"
    out.write_text("  /* snap24.js (v0.24, generated by scripts/snapshot_v24.py; do not edit): the research digest, every checked item dated in the last fortnight. Derived results only. */\n"
                   f"  const SNAP24 = {body};\n  const DIGEST24 = SNAP24.digest;\n")
    print("snap24.js", len(body) // 1024, "KB", d["n"], "items since", since, "from", len(d["publishers"]), "publishers")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
