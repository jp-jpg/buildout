"""Write site/src/snap11.js: the decision loop, valuation, causal statistics and hedge catalog the engine computes from
the snapshot inputs, so the page (a harness for the engine) has them before the first daily run writes ooda.json.

    python scripts/snapshot_v11.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from buildout import ooda  # noqa: E402
from buildout.engine import REGISTRY  # noqa: E402
from buildout.jsonout import clean  # noqa: E402

# the page's own snapshot readings (site/src/data.js, Oct 2026): 36-month inflation 3.06% (>= 2.75%), stock-bond
# correlation +0.15 (> 0), VIX 19.99 (< 20), builders' capex 83% of operating cash flow (> 80%), 2s10s +38bp (not
# inverted); Brent against its 5-year average and the high-yield spread are left unknown
SIGNALS = {"infl": True, "corr": True, "oil": None, "vix": False, "hy": None, "capex": True, "curve": False}

o = clean(ooda.build(ROOT / "site" / "data", str(ROOT / "config.toml"), signals=SIGNALS, as_of="2026-10-21"))
o["snapshot_signals"] = SIGNALS
reg = [{"name": e.name, "title": e.title, "reads": e.reads, "writes": e.writes, "module": e.module, "offline": e.offline, "does": e.does} for e in REGISTRY]
out = ROOT / "site" / "src" / "snap11.js"
out.write_text("  /* generated by scripts/snapshot_v11.py: the engine's decision loop on the snapshot inputs (Oct 21, 2026) */\n"
               f"  const OODA_SNAP = {json.dumps(o, separators=(',', ':'))};\n  const ENGINES_SNAP = {json.dumps(reg, separators=(',', ':'))};\n")
print("wrote", out, out.stat().st_size, "bytes")
