"""Write site/src/snap13.js: the atlas (buildout/atlas.py) on the data reachable from here, so the page carries the
whole learned brain before any daily run. Derived results only (links, weights, layout, indices): no raw prices.

    python scripts/snapshot_v13.py [--cache path.pkl]
"""
from __future__ import annotations

import json
import pickle
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from buildout import atlas  # noqa: E402


def _clean(o):
    import numpy as np
    if isinstance(o, (float, np.floating)):
        o = float(o)
        return None if o != o or o in (float("inf"), float("-inf")) else round(o, 5)
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, (np.bool_,)):
        return bool(o)
    if isinstance(o, dict):
        return {str(k): _clean(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [_clean(v) for v in o]
    return o


def main(argv: list[str]) -> int:
    cache = Path(argv[argv.index("--cache") + 1]) if "--cache" in argv else None
    if cache and cache.exists():
        dl = pickle.loads(cache.read_bytes())
    else:
        dl = atlas.download()
        if cache:
            cache.write_bytes(pickle.dumps(dl))
    r = atlas.build(dl)
    r["findings"] = atlas.summary(r)
    r = _clean(r)
    (ROOT / "buildout" / "assets" / "atlas.json").write_text(json.dumps(r, separators=(",", ":"), ensure_ascii=False))
    out = ROOT / "site" / "src" / "snap13.js"
    js = ("  /* snap13.js (v0.13, generated by scripts/snapshot_v13.py; do not edit): the atlas, learned from every monthly series\n"
          "     reachable when it was built. Derived results only. */\n"
          f"  const ATLAS_SNAP = {json.dumps(r, separators=(',', ':'), ensure_ascii=False)};\n")
    out.write_text(js)
    print(f"wrote {out} {len(js):,} bytes; {r['series']} series, {len(r['nodes'])} nodes, {len(r['links'])} learned links, {len(r['judged'])} judged")
    for f in r["findings"]:
        print(" ", f)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
