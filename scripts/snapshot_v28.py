"""Write site/src/snap28.js (v0.28: the filings engine: its signals and their published sources, the method, its
validation on synthetic data in the SEC's layouts, and the latest real run when one exists) and rebuild snap14 to
snap27 through snapshot_v27. Derived results only: SEC downloads and prices stay in the run's cache.

    python scripts/snapshot_v28.py [--filings-json site/data/filings.json] ... (the v27 flags)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

from buildout import filings  # noqa: E402
import snapshot_v14 as S14  # noqa: E402
import snapshot_v15 as S15  # noqa: E402
import snapshot_v27 as S27  # noqa: E402

S15.EXTRA_CODE += ["buildout/filings.py", "scripts/snapshot_v28.py", "scripts/calibrate_filings.py", ".github/workflows/filings.yml"]


def main(argv: list[str]) -> int:
    S27.main(argv)
    fj = Path(argv[argv.index("--filings-json") + 1]) if "--filings-json" in argv else ROOT / "site" / "data" / "filings.json"
    run = json.loads(fj.read_text()) if fj.exists() else None
    if run is not None and run.get("meta", {}).get("synthetic"):
        run = None
    body = {"status": "run" if run else "awaiting first run",
            "signals": [{"id": k, "name": v[0], "direction": v[1], "reference": v[2], "published": v[3], "family": v[4]} for k, v in filings.SIGNALS.items()],
            "assumptions": {"start": filings.START, "split": filings.SPLIT, "fdr_q": filings.FDR_Q, "block_months": filings.BLOCK,
                            "nw_lags": filings.NW_LAGS, "permutations_diagnostic": filings.N_PERM, "fakes": filings.N_FAKE,
                            "stale_months": filings.STALE_MONTHS, "cost_bp_round_trip": filings.COST_BP, "min_stocks": filings.MIN_STOCKS,
                            "min_group": filings.MIN_GROUP, "min_months": filings.MIN_MONTHS, "horizons": list(filings.HORIZONS), "controls": list(filings.CONTROLS)},
            "verdicts": filings.VERDICTS, "limitations": filings.LIMITATIONS, "validation": filings.validate(), "run": run,
            "calibration": json.loads((ROOT / "buildout" / "assets" / "filings_calibration.json").read_text()),
            "how_to_run": {"laptop": 'python -m buildout filings --ua "Your Name you@example.com" --out out',
                           "github": "the filings-run workflow, weekly on Sunday or by hand from the Actions tab, once the SEC_USER_AGENT variable is set",
                           "text": 'add --text to also download every 10-K and test how much its words changed from the year before (several gigabytes)'}}
    s = json.dumps(S14._clean({"filings": body}), separators=(",", ":"), ensure_ascii=False).replace("</", "<\\/")
    for b in S14.BANNED:
        assert b not in s.lower(), b
    (ROOT / "site" / "src" / "snap28.js").write_text("  /* snap28.js (v0.28, generated by scripts/snapshot_v28.py; do not edit): the filings engine. Derived results only. */\n"
                                                     f"  const SNAP28 = {s};\n")
    print("snap28.js", len(s) // 1024, "KB", "status:", body["status"])
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
