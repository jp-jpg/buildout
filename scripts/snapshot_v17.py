"""Write site/src/snap17.js (the bond lab on today's curve, today's tape, the complexity study and the chronicle's
analogs for now), and rebuild snap14 to snap16 through snapshot_v16 with the v0.17 inputs, since the mind now holds
the chronicle, the Treasury ETFs, the complexity findings and the desks. Derived results only.

    python scripts/snapshot_v17.py --labs-cache labs_dl.pkl --labs-pickle labs_L.pkl --ml-pickle ml_o.pkl --as-pickle as_o.pkl \\
        --rl-pickle rl_o.pkl [--cx-pickle cx_o.pkl]
"""
from __future__ import annotations

import json
import pickle
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

from buildout import bondlab, chronicle, complexity, labs, mind  # noqa: E402
import snapshot_v14 as S14  # noqa: E402
import snapshot_v15 as S15  # noqa: E402
import snapshot_v16 as S16  # noqa: E402

BANNED = S14.BANNED
S15.EXTRA_CODE += ["buildout/bondlab.py", "buildout/chronicle.py", "buildout/complexity.py", "scripts/snapshot_v17.py", "buildout/core/cache.py", "buildout/core/runner.py", "buildout/core/contracts.py", "buildout/core/doctor.py"]
TAPE_KEEP = ("id", "kind", "ticker", "title", "text", "value", "unit", "as_of", "source_url", "publisher", "verification", "checked")


def today_check(K: dict, bonds_in: dict) -> dict | None:
    """The model against today's tape: the 10-year and 30-year moves reported intraday, TLT's reported move."""
    y10, y30, tl = K.get("tp-10y-1022"), K.get("tp-30y-1022"), K.get("tp-tlt-1022")
    if not (y10 and y30 and tl):
        return None
    grab = lambda it: float(re.search(r"(\d+) basis points", it["text"]).group(1)) / 1e4 if re.search(r"(\d+) basis points", it["text"]) else None
    d10, d30 = grab(y10), grab(y30)
    if d10 is None or d30 is None:
        return None
    c = bonds_in["curve"]
    sc = bondlab.scenario(c, bonds_in["_funds"], c["10y"] - d10, c["30y"] - d30)
    return {"d10": -d10, "d30": -d30, "model_tlt": sc["TLT"]["change"], "model_ief": sc["IEF"]["change"], "actual_tlt": tl["value"] / 100,
            "yield_time": "11:13 a.m. ET", "tlt_time": "1:05 p.m. ET", "src": ["tp-10y-1022", "tp-30y-1022", "tp-tlt-1022"]}


def main(argv: list[str]) -> int:
    get = lambda k: pickle.loads(Path(argv[argv.index(k) + 1]).read_bytes()) if k in argv and Path(argv[argv.index(k) + 1]).exists() else None
    dl = get("--labs-cache") or labs.download()
    S = labs.shiller(dl)
    cx = get("--cx-pickle") or complexity.build(dl)
    chron = chronicle.build(S)
    know = mind.load_knowledge()
    K = {k["id"]: k for k in know}
    curve, facts, meta = bondlab.from_knowledge(know)
    bonds = bondlab.build(curve, facts, S)
    bonds["facts"], bonds["curve_meta"] = facts, meta
    bonds["_funds"] = bondlab.setup(curve, facts)
    bonds["today"] = today_check(K, bonds)
    del bonds["_funds"]
    orig = mind.build
    mind.build = lambda *a, **kw: orig(*a, **kw, chron=chron, bonds=bonds, cx=cx)
    try:
        S16.main(argv)
    finally:
        mind.build = orig
    tape = [{k: x.get(k) for k in TAPE_KEEP if x.get(k) is not None} for x in know if x.get("cluster") == "tape"]
    bfacts = [{k: x.get(k) for k in TAPE_KEEP if x.get(k) is not None} for x in know if x.get("cluster") == "bonds"]
    snap = {"bonds": bonds, "tape": tape, "bond_facts": bfacts, "complexity": cx, "chronicle": {"now": chron["now"], "episodes": [
        {"id": n["id"], "name": n["n"], "start": n["start"], "end": n["end"], "dd": n["dd"], "dy": n["dy"], "text": n["t"]} for n in chron["nodes"] if n["k"] == "episode"],
        "months": len([n for n in chron["nodes"] if n["k"] == "month"])}}
    snap = S14._clean(snap)
    body = json.dumps(snap, separators=(",", ":"), ensure_ascii=False).replace("</", "<\\/")
    for b in BANNED:
        assert b not in body.lower(), b
    out = ROOT / "site" / "src" / "snap17.js"
    out.write_text("  /* snap17.js (v0.17, generated by scripts/snapshot_v17.py; do not edit): the bond lab on today's Treasury curve,\n"
                   "     today's tape, the complexity study and the chronicle. Derived results only. */\n"
                   f"  const SNAP17 = {body};\n  const BONDS17 = SNAP17.bonds, TAPE17 = SNAP17.tape, CX17 = SNAP17.complexity, CHRON17 = SNAP17.chronicle;\n")
    print("snap17.js", len(body) // 1024, "KB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
