"""Write site/src/snap14.js: the labs (buildout/labs.py), the unified mind (buildout/mind.py) and the engine's own source
for the code appendix. Derived results only: indicator readings are shipped as ratios and oscillator values, never as
raw price series.

    python scripts/snapshot_v14.py [--labs-cache labs_dl.pkl] [--labs-pickle labs_L.pkl]
"""
from __future__ import annotations

import json
import pickle
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from buildout import labs, mind, voices  # noqa: E402

BANNED = (chr(0x2014), "inter" "section", "load" "-bearing")
CODE_FILES = ["buildout/mind.py", "buildout/ontology.py", "buildout/labs.py", "buildout/games2.py", "buildout/atlas.py", "buildout/brain_robust.py",
              "buildout/voices.py", "buildout/reasoner.py", "buildout/thinking.py", "buildout/ooda.py", "buildout/hedgebook.py", "buildout/mcp_server.py",
              "buildout/valuation.py", "buildout/games.py", "buildout/field.py", "buildout/discovery.py", "buildout/causal_stats.py", "buildout/brain.py",
              "buildout/robust.py", "buildout/decisions.py", "buildout/policy.py", "buildout/accounting.py", "buildout/microstructure.py",
              "buildout/roc.py", "buildout/research.py", "buildout/engine.py", "buildout/pipeline.py", "buildout/analytics/robust_bt.py",
              "buildout/analytics/options.py", "buildout/analytics/sizing.py", "buildout/analytics/hedge.py", "buildout/analytics/regime.py",
              "buildout/analytics/risk.py", "buildout/analytics/stress.py", "buildout/analytics/vol.py", "buildout/analytics/backtest.py",
              "scripts/build_knowledge.py", "scripts/snapshot_v14.py", ".github/workflows/daily.yml"]


def _clean(o):
    import numpy as np
    if isinstance(o, (float, np.floating)):
        o = float(o)
        return None if o != o or o in (float("inf"), float("-inf")) else round(o, 6)
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, (np.bool_,)):
        return bool(o)
    if isinstance(o, dict):
        return {str(k): _clean(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [_clean(v) for v in o]
    return o


def labs_view(L: dict) -> dict:
    return labs.public(L)


def code_view() -> list[dict]:
    out = []
    for rel in CODE_FILES:
        p = ROOT / rel
        if not p.exists():
            continue
        src = p.read_text()
        low = src.lower()
        for b in BANNED:
            if b in low:
                raise SystemExit(f"{rel} contains banned text {b!r}; fix the source before shipping it to the page")
        doc = ""
        m = re.match(r'\s*"""(.*?)"""', src, re.S)
        if m:
            doc = m.group(1).strip().split("\n\n")[0].replace("\n", " ")
        out.append({"path": rel, "lines": src.count("\n") + 1, "doc": doc[:400], "src": src})
    return out


def main(argv: list[str]) -> int:
    lp = Path(argv[argv.index("--labs-pickle") + 1]) if "--labs-pickle" in argv else None
    know = mind.load_knowledge()
    K = {k["id"]: k for k in know}
    cape_now = (K.get("val-cape-2026-10-20") or {}).get("value")
    if lp and lp.exists():
        L = pickle.loads(lp.read_bytes())
    else:
        cache = Path(argv[argv.index("--labs-cache") + 1]) if "--labs-cache" in argv else None
        dl = pickle.loads(cache.read_bytes()) if cache and cache.exists() else labs.download()
        L = labs.build(dl, cape_now=cape_now)
    L["findings"] = labs.summary(L)
    atlas = json.loads((ROOT / "buildout/assets/atlas.json").read_text())
    rs = (ROOT / "site/src/research.js").read_text()
    m = re.search(r'"latest":\{"month":"([0-9-]+)","corr":([-0-9.e]+),"infl_avg":([-0-9.e]+)\}', rs)
    research_latest = {"month": m.group(1), "corr": float(m.group(2)), "infl_avg": float(m.group(3))} if m else None
    G = mind.build(atlas, voices.load(), know, mind.load_countries(), L, research_latest)
    (ROOT / "buildout/assets/mind.json").write_text(json.dumps(_clean(mind.compact(G)), separators=(",", ":"), ensure_ascii=False))
    st = mind.stats(G)
    snap = {"labs": _clean(labs_view(L)), "mind": _clean(mind.compact(G)), "stats": st, "code": code_view(),
            "knowledge_note": json.loads((ROOT / "buildout/assets/knowledge.json").read_text())["note"]}
    body = json.dumps(snap, separators=(",", ":"), ensure_ascii=False).replace("</", "<\\/")
    for b in BANNED:
        assert b not in body.lower(), b
    out = ROOT / "site" / "src" / "snap14.js"
    js = ("  /* snap14.js (v0.14, generated by scripts/snapshot_v14.py; do not edit): the labs, the unified mind and the engine's\n"
          "     source for the code appendix. Derived results only. */\n"
          f"  const SNAP14 = {body};\n  const LABS_SNAP = SNAP14.labs, MIND_SNAP = SNAP14.mind, CODE_SNAP = SNAP14.code;\n")
    out.write_text(js)
    print(f"wrote {out} {len(js):,} bytes; mind {st['nodes']} nodes, {st['edges']} edges, {st['signals']} signals; code {len(snap['code'])} files")
    for f in L["findings"]:
        print(" ", f)
    return 0


if __name__ == "__main__":
    # run alone, this writes the v0.14 mind over the current one; the chain starts at the newest snapshot script
    if "--force-v14" not in sys.argv:
        raise SystemExit("snapshot_v14.py is a library for the later snapshots; run scripts/snapshot_v22.py (or pass --force-v14)")
    raise SystemExit(main([a for a in sys.argv[1:] if a != "--force-v14"]))
