"""Write site/src/snap23.js (the engine's parameters, Theta: every fitted matrix with its shape, the algorithm that shaped
it, its objective, its data, its refit schedule and the desks it feeds) and rebuild snap14 to snap22 through
snapshot_v22, so the inventory is read from the same run as every other number on the page. Derived results only.

    python scripts/snapshot_v23.py --dec-pickle dec_o.pkl --pf-pickle pf_o.pkl --rl-pickle rl_o.pkl --ml-pickle ml_o.pkl \\
        --geo-pickle geo_o.pkl ... (the v22 flags)
"""
from __future__ import annotations

import json
import pickle
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

from buildout import mind, parameters  # noqa: E402
import snapshot_v14 as S14  # noqa: E402
import snapshot_v15 as S15  # noqa: E402
import snapshot_v22 as S22  # noqa: E402

S15.EXTRA_CODE += ["buildout/parameters.py", "scripts/snapshot_v23.py"]


def main(argv: list[str]) -> int:
    get = lambda k: pickle.loads(Path(argv[argv.index(k) + 1]).read_bytes()) if k in argv and Path(argv[argv.index(k) + 1]).exists() else None
    assets = ROOT / "buildout" / "assets"
    def inventory():
        return S14._clean(parameters.build(dec=get("--dec-pickle"), pf=get("--pf-pickle"), rlo=get("--rl-pickle"), mlo=get("--ml-pickle"), geo=get("--geo-pickle"),
                                           atlas=json.loads((assets / "atlas.json").read_text()), brain=json.loads((assets / "brain_graph.json").read_text()),
                                           mind=json.loads((assets / "mind.json").read_text())))
    o = inventory()
    orig = mind.build
    mind.build = lambda *a, **kw: orig(*a, **kw, theta=o)
    try:
        S22.main(argv)
    finally:
        mind.build = orig
    o = inventory()                        # the knowledge-graph counts from the mind just rebuilt, so the two agree
    body = json.dumps({"parameters": o}, separators=(",", ":"), ensure_ascii=False).replace("</", "<\\/")
    for b in S14.BANNED:
        assert b not in body.lower(), b
    out = ROOT / "site" / "src" / "snap23.js"
    out.write_text("  /* snap23.js (v0.23, generated by scripts/snapshot_v23.py; do not edit): the engine's parameters, Theta. Derived results only. */\n"
                   f"  const SNAP23 = {body};\n  const THETA23 = SNAP23.parameters;\n")
    print("snap23.js", len(body) // 1024, "KB", o["total"], "numbers in", len(o["entries"]), "objects")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
