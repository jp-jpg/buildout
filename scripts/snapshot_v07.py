"""Write site/src/snap7.js: the reasoner's measured factor covariances, by regime, from the public research datasets.

    python scripts/snapshot_v07.py /path/to/research/csvs      # shiller.csv, cpi.csv, y10.csv, brent.csv, vix.csv, gold.csv
"""
import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from buildout.reasoner import factor_cov  # noqa: E402
from buildout.research import SOURCES  # noqa: E402

raw = {k: pd.read_csv(Path(sys.argv[1]) / f"{k}.csv") for k in SOURCES}
cov = factor_cov(raw)
out = Path(__file__).resolve().parents[1] / "site" / "src" / "snap7.js"
out.write_text("  /* generated by scripts/snapshot_v07.py: measured 3-month factor covariances by regime (market, ai, dy, oil, gold) */\n"
               f"  const REASON_SNAP = {json.dumps(cov, separators=(',', ':'))};\n")
print("wrote", out, {k: v["months"] for k, v in cov["regimes"].items()})
