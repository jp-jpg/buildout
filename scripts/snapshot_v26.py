"""Write site/src/snap26.js (v0.26: the edge lab: the hypothesis factory's funnel against its placebos, every
surviving edge with its mechanism and untouched test years, the edge book, the families, and the unusual data with the
lag at which each value is knowable) and rebuild snap14 to snap25 through snapshot_v25. Derived results only: the raw
unusual data stay in the run's cache, never in the repository.

    python scripts/snapshot_v26.py --discovery-json discovery_o.json --unusual-pickle unusual_dl.pkl ... [--preaudit-json discovery_o_preaudit.json] (the v25 flags)
"""
from __future__ import annotations

import json
import pickle
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

from buildout import discovery, unusual  # noqa: E402
import snapshot_v14 as S14  # noqa: E402
import snapshot_v15 as S15  # noqa: E402
import snapshot_v25 as S25  # noqa: E402

S15.EXTRA_CODE += ["buildout/unusual.py", "scripts/snapshot_v26.py"]


def preaudit(o: dict) -> dict:
    """The few headline numbers of the run before the independent audit, for the page's before-and-after table."""
    f = {r["key"]: r for r in o["funnel"]}
    t, ea = o["book"].get("test", {}), o.get("early") or {}
    fe = {r["key"]: r for r in ea.get("funnel", [])}
    return {"bh": f["bh"]["real"], "bh_cut": o["bh_p_threshold"], "distinct": f["distinct"]["real"], "null_distinct_expected": f["distinct"].get("expected_false_real"),
            "test_data": f["test_data"]["real"], "test_t2": f["test_t2"]["real"], "book_sharpe": t.get("sharpe"), "book_t": t.get("t"), "book_vol": t.get("vol_annual"),
            "early_distinct": fe.get("distinct", {}).get("real"), "early_book_sharpe": (ea.get("book") or {}).get("test", {}).get("sharpe"),
            "long_edges": sum(1 for e in o["edges"] if e["block"] == "long"), "composite_edges": sum(1 for e in o["edges"] if e["kind"] == "compositions")}


def main(argv: list[str]) -> int:
    S25.main(argv)
    d = json.loads(Path(argv[argv.index("--discovery-json") + 1]).read_text())
    udl = pickle.loads(Path(argv[argv.index("--unusual-pickle") + 1]).read_bytes()) if "--unusual-pickle" in argv else None
    um = unusual.meta(udl)
    body = {"discovery": d, "unusual": um, "summary": discovery.summary(d)}
    if "--preaudit-json" in argv:
        body["preaudit"] = preaudit(json.loads(Path(argv[argv.index("--preaudit-json") + 1]).read_text()))
    s = json.dumps(S14._clean(body), separators=(",", ":"), ensure_ascii=False).replace("</", "<\\/")
    for b in S14.BANNED:
        assert b not in s.lower(), b
    (ROOT / "site" / "src" / "snap26.js").write_text("  /* snap26.js (v0.26, generated by scripts/snapshot_v26.py; do not edit): the edge lab. Derived results only. */\n"
                                                     f"  const SNAP26 = {s};\n")
    print("snap26.js", len(s) // 1024, "KB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
