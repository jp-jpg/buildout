"""Write site/src/snap9.js: the brain's six standardized monthly series (oil, CPI, 10-year, stocks, VIX, gold), so the
page can learn the causal order and the time-varying links itself.

    python scripts/snapshot_v09.py /path/to/research/csvs      # shiller.csv, cpi.csv, y10.csv, brent.csv, vix.csv, gold.csv
"""
import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from buildout.brain import series_block  # noqa: E402
from buildout.research import SOURCES, tidy  # noqa: E402

raw = {k: pd.read_csv(Path(sys.argv[1]) / f"{k}.csv") for k in SOURCES}
block = series_block(tidy(raw))
out = Path(__file__).resolve().parents[1] / "site" / "src" / "snap9.js"
out.write_text("  /* generated by scripts/snapshot_v09.py: standardized monthly changes (derived from public datasets) */\n"
               f"  const BRAIN_SERIES = {json.dumps(block, separators=(',', ':'))};\n")
print("wrote", out, block["dates"][0], "to", block["dates"][-1], len(block["dates"]), "months")
