"""Write site/src/snap16.js (technical and fundamental analysis, the reinforcement-learning agent, the data connections
and the distribution scorecard), and refresh snap14.js and snap15.js through snapshot_v15 with the v0.16 inputs, since
the mind now reads the technicals and the agent too. Derived results only: readings, signals, ratios and scores.

    python scripts/snapshot_v16.py --labs-cache labs_dl.pkl --labs-pickle labs_L.pkl --ml-pickle ml_o.pkl --as-pickle as_o.pkl [--rl-pickle rl_o.pkl]
"""
from __future__ import annotations

import datetime as dt
import json
import pickle
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

import pandas as pd  # noqa: E402

from buildout import datahub, fundamentals, labs, mind, rl, statements, technicals  # noqa: E402
import snapshot_v14 as S14  # noqa: E402
import snapshot_v15 as S15  # noqa: E402

BANNED = S14.BANNED
SERIES = {"brent": "Brent crude (daily, EIA spot)", "wti": "WTI crude (daily)", "gas": "Henry Hub gas (daily)", "vix": "VIX (daily; an index, not tradable)"}
S15.EXTRA_CODE += ["buildout/technicals.py", "buildout/statements.py", "buildout/rl.py", "buildout/datahub.py", "scripts/snapshot_v16.py"]


def tech_view(dl) -> dict:
    out = {}
    for k, name in SERIES.items():
        s = labs.daily(dl, k)
        if len(s) < 300:
            continue
        a = technicals.analyze(pd.DataFrame({"close": s}), name)
        a["text"] = technicals.text(a)
        a["source"] = "GitHub mirror of the public dataset"
        out[k] = a
    return out


def fund_view() -> dict:
    """The filings fixture carries a subset of tags (cash flow, capex, revenue, operating income, debt): the ratios it
    allows are computed; the scores mark the tests it cannot run as unknown. The daily Action reads full company facts."""
    u = fundamentals.parse_fixture(ROOT / "tests" / "fixtures" / "sec_facts_2026q3.txt")
    return {t: statements.analyze(f, t) for t, f in statements.from_fixture_rows(u).items()}


def distribution_view(know: list[dict]) -> list[dict]:
    keep = ("id", "kind", "ticker", "title", "text", "value", "unit", "as_of", "source_url", "publisher", "primary", "verification", "checked", "speaker")
    return [{k: x.get(k) for k in keep if x.get(k) is not None} for x in know if x.get("cluster") == "distribution"]


def main(argv: list[str]) -> int:
    get = lambda k: pickle.loads(Path(argv[argv.index(k) + 1]).read_bytes()) if k in argv and Path(argv[argv.index(k) + 1]).exists() else None
    dl = get("--labs-cache") or labs.download()
    rlo = get("--rl-pickle") or rl.build(dl)
    tech = tech_view(dl)
    # the mind reads the agent and the technicals: rebuild snap14 and snap15 with them
    orig_build = mind.build
    mind.build = lambda *a, **kw: orig_build(*a, **kw, rlo=rlo, tech=tech)
    try:
        S15.main(argv)
    finally:
        mind.build = orig_build
    know = mind.load_knowledge()
    conn = datahub.check(timeout=8)
    snap = {"technicals": {"as_of": dt.date.today().isoformat(), "assets": tech, "note": "Built from the public daily series this workspace can reach; the daily Action adds every holding from Databento, Yahoo or Stooq."},
            "statements": {"companies": fund_view(), "note": "From the SEC facts fixture (a subset of tags, fetched Oct 21, 2026); the daily Action reads full company facts."},
            "rl": S14._clean(rlo), "connections": conn, "connections_note": "Checked from the build workspace, which can reach only GitHub and package registries; the daily Action checks again with your secrets.",
            "distribution": distribution_view(know)}
    snap = S14._clean(snap)
    body = json.dumps(snap, separators=(",", ":"), ensure_ascii=False).replace("</", "<\\/")
    for b in BANNED:
        assert b not in body.lower(), b
    out = ROOT / "site" / "src" / "snap16.js"
    out.write_text("  /* snap16.js (v0.16, generated by scripts/snapshot_v16.py; do not edit): technical and fundamental analysis, the\n"
                   "     reinforcement-learning agent, the data connections and the distribution scorecard. Derived results only. */\n"
                   f"  const SNAP16 = {body};\n  const TA_SNAP = SNAP16.technicals, FA_SNAP = SNAP16.statements, RL_SNAP = SNAP16.rl, CONN_SNAP = SNAP16.connections, DIST_SNAP = SNAP16.distribution;\n")
    print(f"wrote snap16 {out.stat().st_size:,} bytes; technicals {list(tech)}; rl {rlo['best']}")
    for f in rlo["findings"]:
        print(" ", f)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
