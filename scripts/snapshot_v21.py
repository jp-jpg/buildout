"""Write site/src/snap21.js (the matrix shortcut: the mind's board computed in one batched pass, spectral neighbours
of key nodes, and the measured speed of every shortcut against the step-by-step version) and rebuild snap14 to snap20
through snapshot_v20, so the mind carries the new concepts and the Pearl facts. Derived results only.

    python scripts/snapshot_v21.py --pf-pickle pf_o.pkl --dec-pickle dec_o.pkl --labs-cache labs_dl.pkl ... (the v20 flags)
"""
from __future__ import annotations

import json
import pickle
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

from buildout import mind, voices  # noqa: E402
from buildout.core import bench  # noqa: E402
import snapshot_v14 as S14  # noqa: E402
import snapshot_v15 as S15  # noqa: E402
import snapshot_v20 as S20  # noqa: E402

S15.EXTRA_CODE += ["buildout/core/bench.py", "scripts/snapshot_v21.py"]
# whole-engine builds, timed in the v0.21 build session on the same two-CPU machine: the v0.20 code against the v0.21 code
# (scan-based regimes, batched EM starts, the batched neural ensemble); each pair produced the same findings
ENGINES = {"decide": {"what": "Decision engine, full build", "before_s": 93.35, "after_s": 32.51},
           "portfolio": {"what": "Portfolio engine, full build", "before_s": 23.9, "after_s": 9.2},
           "nn": {"what": "Five-network ensemble, one fit", "before_s": 0.726, "after_s": 0.400}}
RELATED = ["c:kalman", "c:hidden-markov-model", "c:proof-of-useful-work", "c:matrix-multiplication", "c:duration", "c:gpu", "c:stock-bond-correlation", "c:overfitting",
           "etf:tlt", "c:bitcoin"]


def main(argv: list[str]) -> int:
    get = lambda k: pickle.loads(Path(argv[argv.index(k) + 1]).read_bytes()) if k in argv and Path(argv[argv.index(k) + 1]).exists() else None
    S20.main(argv)
    G = json.loads((ROOT / "buildout" / "assets" / "mind.json").read_text())
    M = mind.Mind(G, voices.Library(voices.load()))
    snap = {"board": M.board(), "related": {i: M.related(i, 8) for i in RELATED if i in M.idx}, "bench": bench.matrix_bench(get("--labs-cache")), "engines": ENGINES}
    snap = S14._clean(snap)
    body = json.dumps({"matrix": snap}, separators=(",", ":"), ensure_ascii=False).replace("</", "<\\/")
    for b in S14.BANNED:
        assert b not in body.lower(), b
    out = ROOT / "site" / "src" / "snap21.js"
    out.write_text("  /* snap21.js (v0.21, generated by scripts/snapshot_v21.py; do not edit): the matrix shortcut, measured. Derived results only. */\n"
                   f"  const SNAP21 = {body};\n  const MX21 = SNAP21.matrix;\n")
    print("snap21.js", len(body) // 1024, "KB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
