"""Write site/src/snap22.js (the shape of the market: covariance geometry and its era map, today's analogs and the
placebo that tests them, the eigenvalues of the world's markets against the Marchenko-Pastur edge, persistent homology,
transport analogs, the Levy area, long memory, volatility drag and every test with its false-discovery q) and rebuild
snap14 to snap21 through snapshot_v21, so the mind carries the geometry. Derived results only.

    python scripts/snapshot_v22.py --geo-pickle geo_o.pkl ... (the v21 flags)
"""
from __future__ import annotations

import json
import pickle
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

from buildout import atlas, geometry, labs, mind  # noqa: E402
import snapshot_v14 as S14  # noqa: E402
import snapshot_v15 as S15  # noqa: E402
import snapshot_v21 as S21  # noqa: E402

S15.EXTRA_CODE += ["buildout/geometry.py", "scripts/snapshot_v22.py"]


def compact(o: dict) -> dict:
    """What the desk draws: everything but the per-month series it does not plot."""
    out = {k: o[k] for k in ("notes", "labels", "covariance", "transport", "scaling", "compounding", "engine_model", "tests", "findings") if k in o}
    p = o["paths"]
    out["paths"] = {"window": p["window"], "series": p["series"], "now": p["now"], "test": p["test"]}
    if "spectrum" in o:
        out["spectrum"] = o["spectrum"]
    if "topology" in o:
        out["topology"] = o["topology"]
    return out


def main(argv: list[str]) -> int:
    get = lambda k: pickle.loads(Path(argv[argv.index(k) + 1]).read_bytes()) if k in argv and Path(argv[argv.index(k) + 1]).exists() else None
    geo = get("--geo-pickle")
    if geo is None:
        adl = atlas.download(fred=False)
        geo = geometry.build(get("--labs-cache") or labs.download(), adl["raw"], atlas_dl=adl)
    geo = S14._clean(compact(geo))
    orig = mind.build
    mind.build = lambda *a, **kw: orig(*a, **kw, geo=geo)
    try:
        S21.main(argv)
    finally:
        mind.build = orig
    body = json.dumps({"geometry": geo}, separators=(",", ":"), ensure_ascii=False).replace("</", "<\\/")
    for b in S14.BANNED:
        assert b not in body.lower(), b
    out = ROOT / "site" / "src" / "snap22.js"
    out.write_text("  /* snap22.js (v0.22, generated by scripts/snapshot_v22.py; do not edit): the shape of the market. Derived results only. */\n"
                   f"  const SNAP22 = {body};\n  const GEO22 = SNAP22.geometry;\n")
    print("snap22.js", len(body) // 1024, "KB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
