"""Write site/src/snap20.js (the portfolio engine: today's mix, its regimes, every policy walked forward, the learner,
ten simulated years and the stress replays) and rebuild snap14 to snap19 through snapshot_v19 with the portfolio in
the mind. Derived results only.

    python scripts/snapshot_v20.py --pf-pickle pf_o.pkl --dec-pickle dec_o.pkl --labs-cache labs_dl.pkl ... (the v19 flags)
"""
from __future__ import annotations

import json
import pickle
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

from buildout import atlas, labs, mind, portfolio  # noqa: E402
import snapshot_v14 as S14  # noqa: E402
import snapshot_v15 as S15  # noqa: E402
import snapshot_v19 as S19  # noqa: E402

S15.EXTRA_CODE += ["buildout/portfolio.py", "scripts/snapshot_v20.py"]


def main(argv: list[str]) -> int:
    get = lambda k: pickle.loads(Path(argv[argv.index(k) + 1]).read_bytes()) if k in argv and Path(argv[argv.index(k) + 1]).exists() else None
    pf = get("--pf-pickle")
    if pf is None:
        pf = portfolio.build(get("--labs-cache") or labs.download(), atlas.download(fred=False)["raw"])
    pf["findings"] = portfolio.summary(pf)
    pf = S14._clean(pf)
    orig = mind.build
    mind.build = lambda *a, **kw: orig(*a, **kw, pf=pf)
    try:
        S19.main(argv)
    finally:
        mind.build = orig
    body = json.dumps({"portfolio": pf}, separators=(",", ":"), ensure_ascii=False).replace("</", "<\\/")
    for b in S14.BANNED:
        assert b not in body.lower(), b
    out = ROOT / "site" / "src" / "snap20.js"
    out.write_text("  /* snap20.js (v0.20, generated by scripts/snapshot_v20.py; do not edit): the portfolio engine. Derived results only. */\n"
                   f"  const SNAP20 = {body};\n  const PF20 = SNAP20.portfolio;\n")
    print("snap20.js", len(body) // 1024, "KB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
