"""Write site/src/snap29.js (v0.29: the futures engine: its markets and signals with their published sources, its
validation and calibration on synthetic data, the long run on pysystemtrade's published prices to March 2024, and the
Databento run when one exists) and rebuild snap14 to snap28 through snapshot_v28. Derived results only: futures prices
stay in the run's cache.

    python scripts/snapshot_v29.py [--futures-carver-json buildout/assets/futures_pysystemtrade.json]
                                   [--futures-json site/data/futures.json] ... (the v28 flags)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

from buildout import futures  # noqa: E402
import snapshot_v14 as S14  # noqa: E402
import snapshot_v15 as S15  # noqa: E402
import snapshot_v28 as S28  # noqa: E402

S15.EXTRA_CODE += ["buildout/futures.py", "scripts/snapshot_v29.py", "scripts/calibrate_futures.py", ".github/workflows/futures.yml"]


def _run(path: Path) -> dict | None:
    if not path.exists():
        return None
    o = json.loads(path.read_text())
    return None if (o.get("meta") or {}).get("synthetic") else o


def main(argv: list[str]) -> int:
    S28.main(argv)
    arg = lambda k, d: Path(argv[argv.index(k) + 1]) if k in argv else d
    long_run = _run(arg("--futures-carver-json", ROOT / "buildout" / "assets" / "futures_pysystemtrade.json"))
    live = _run(arg("--futures-json", ROOT / "site" / "data" / "futures.json"))
    cal = ROOT / "buildout" / "assets" / "futures_calibration.json"
    body = {"status": "databento run" if live else ("long record only" if long_run else "awaiting first run"),
            "signals": [{"id": k, "name": v[0], "direction": v[1], "reference": v[2], "published": v[3]} for k, v in futures.SIGNALS.items()],
            "markets": [{"code": k, "name": v[0], "databento_root": v[1], "pysystemtrade": v[2], "cftc_code": v[3], "class": v[5], "cost_bp": v[6]}
                        for k, v in futures.MARKETS.items()],
            "designs": futures.DESIGNS,
            "assumptions": {"start": futures.START, "split": futures.SPLIT, "fdr_q": futures.FDR_Q, "min_markets_xs": futures.MIN_MARKETS_XS,
                            "min_markets_ts": futures.MIN_MARKETS_TS, "min_months": futures.MIN_MONTHS, "vol_com_days": futures.VOL_COM,
                            "cot_lag_days": futures.COT_LAG_DAYS, "fakes": futures.N_FAKE, "faded_sharpe": futures.FADED_SHARPE},
            "verdicts": futures.VERDICTS, "limitations": futures.LIMITATIONS, "validation": futures.validate(),
            "calibration": json.loads(cal.read_text()) if cal.exists() else None,
            "runs": {"pysystemtrade": long_run, "databento": live},
            "how_to_run": {"laptop": "with DATABENTO_API_KEY set, run python -m buildout futures --source databento --out site/data",
                           "github": "the futures-run workflow, weekly on Saturday or by hand from the Actions tab, once the DATABENTO_API_KEY secret is set",
                           "long": "python -m buildout futures --source pysystemtrade --out site/data (no key; the published record to March 2024)"}}
    s = json.dumps(S14._clean({"futures": body}), separators=(",", ":"), ensure_ascii=False).replace("</", "<\\/")
    for b in S14.BANNED:
        assert b not in s.lower(), b
    (ROOT / "site" / "src" / "snap29.js").write_text("  /* snap29.js (v0.29, generated by scripts/snapshot_v29.py; do not edit): the futures engine. Derived results only. */\n"
                                                     f"  const SNAP29 = {s};\n")
    print("snap29.js", len(s) // 1024, "KB", "status:", body["status"])
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
