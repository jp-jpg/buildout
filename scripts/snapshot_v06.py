"""Write site/src/snap6.js: the dated snapshot of the v0.6 engine outputs the page shows until the daily run replaces them.

    python -m buildout brain --data <folder> --out <dir>; python -m buildout buyside --data <folder> --out <dir>
    python scripts/snapshot_v06.py <dir>
"""
import json
import sys
from pathlib import Path


def r(o, d=4):
    if isinstance(o, float):
        return round(o, d)
    if isinstance(o, dict):
        return {k: r(v, d) for k, v in o.items()}
    if isinstance(o, list):
        return [r(v, d) for v in o]
    return o


def main(src: str) -> None:
    d = Path(src)
    brain = json.loads((d / "brain.json").read_text())
    buy = json.loads((d / "buyside.json").read_text())
    srcs = json.loads((d / "sources.json").read_text())
    brain_s = {"regimes": {k: {"start": v["start"], "end": v["end"], "months": v["months"],
                               "edges": {e: {"w": x["w"], "se": x["se"]} for e, x in v["edges"].items()}} for k, v in brain["regimes"].items()},
               "state": brain["state"], "corr": brain["y10_eq_corr"]}
    out = "/* snap6.js: generated by scripts/snapshot_v06.py from the engine's brain, buyside and sources outputs. Do not edit. */\n"
    out += f"  const BRAIN_SNAP = {json.dumps(r(brain_s))};\n"
    out += f"  const BUY_SNAP = {json.dumps(r(buy))};\n"
    out += f"  const SOURCES_SNAP = {json.dumps({'count': srcs['count'], 'by_kind': srcs['by_kind']})};\n"
    Path(__file__).resolve().parent.parent.joinpath("site", "src", "snap6.js").write_text(out)
    print("wrote site/src/snap6.js", len(out), "bytes")


if __name__ == "__main__":
    main(sys.argv[1])
